function styleOf(entry: PromptEntry): Style {
  const group = STYLE_BY_GROUP[`${entry.category}|${entry.subcategory}`] ?? STYLE_BY_GROUP[entry.category];
  if (entry.category === 'AI 文字提示詞（Alice 版）' || entry.category === '年代造型' || entry.category === '懷舊插畫風格') return group!;
  const declared = entry.prompt.match(/【拍攝風格】([^\n【]+)/)?.[1];
  if (declared) for (const [style, pattern] of STYLE_RULES) if (pattern.test(declared)) return style;
  if (group) return group;
  for (const [style, pattern] of STYLE_RULES) if (pattern.test(entry.prompt)) return style;
  return '寫實攝影';
}

export function classifyPrompt(entry: PromptEntry): Taxonomy {
  const [theme, subtheme] = THEME_BY_SUBCATEGORY[`${entry.category}|${entry.subcategory}`] ?? THEME_BY_CATEGORY[entry.category] ?? ['實用設計與圖卡'];
  return {theme, subtheme: subtheme || entry.subcategory, style: styleOf(entry)};
}
